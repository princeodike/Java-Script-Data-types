
// 1. JavaScript Data Types

// String
var name = "John";

// Number
var age = 25;

// Boolean
var isStudent = true;

// Null
var address = null;

// Undefined
var phoneNumber;

console.log(name);
console.log(age);
console.log(isStudent);
console.log(address);
console.log(phoneNumber);

// 2. String Properties and Methods
var myName = "JOHN DOE";
console.log(myName);
console.log(myName.length);
console.log(myName.toLowerCase());
console.log(myName.toUpperCase());
console.log(myName.trim());
console.log(myName.includes("JOHN"));

// 3. Mathematical Operations
const a = 25;
const b = 7;

console.log(a+b)
console.log(a-b);
console.log(a * b);
console.log(a / b);
console.log(a ** b);
console.log(a % b);

// 4. Working with the Math Object
console.log(Math.PI);
console.log(Math.random() * 100);
console.log(Math.floor(Math.random() * 50) + 1);
console.log(Math.floor(45.89));
